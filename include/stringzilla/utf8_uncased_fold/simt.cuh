/**
 *  @brief The page of folded images each run of 64 runes reads, up to U+1E921, the last rune that
 *      folds; page zero folds nothing, which is also every rune past the table.
 *
 *  An image is a rune's folded UTF-8, the first byte in the lowest, or zero for a rune folding to
 *  itself. An image whose first byte is a continuation byte, which no UTF-8 begins with, holds in
 *  its upper bytes the index of an expansion instead: the folded bytes, at most six, the length in
 *  bits 48 to 55, and a bit per byte ending a rune from bit 56. The three arrays are generated:
 *
 *  @code{.c}
 *  for (sz_size_t page = 0; page != (0x1E921 >> 6) + 1; ++page) {
 *      sz_u32_t page_images[64] = {0};
 *      int folds = 0;
 *      for (sz_size_t offset = 0; offset != 64; ++offset) {
 *          sz_rune_t const rune = (sz_rune_t)(page * 64 + offset), folded[3];
 *          if (rune >= 0xD800 && rune <= 0xDFFF) continue;
 *          sz_size_t const count = sz_unicode_fold_codepoint_(rune, folded);
 *          if (count == 1 && folded[0] == rune) continue;
 *          sz_u8_t bytes[12];
 *          sz_size_t length = 0, rune_ends = 0;
 *          for (sz_size_t index = 0; index != count; ++index)
 *              length += sz_rune_encode(folded[index], bytes + length), rune_ends |= 1u << (length - 1);
 *          sz_u64_t image = 0;
 *          for (sz_size_t index = 0; index != length; ++index) image |= (sz_u64_t)bytes[index] << (8 * index);
 *          if (count == 1) page_images[offset] = (sz_u32_t)image;
 *          else expansions[expansions_count] = image | (sz_u64_t)length << 48 | (sz_u64_t)rune_ends << 56,
 *               page_images[offset] = 0x80u | (sz_u32_t)expansions_count++ << 8;
 *          folds = 1;
 *      }
 *      if (folds) pages[page] = images_pages, append(images, page_images), ++images_pages;
